// Bucket an arbitrary hex into one of the shared GROUPS so the DMC library can
// reuse the same group-filter pills as the Kona (quilt) library.
function colorGroup(hex) {
  const r = parseInt(hex.slice(1, 3), 16) / 255, g = parseInt(hex.slice(3, 5), 16) / 255, b = parseInt(hex.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  const l = (max + min) / 2;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  let h = 0;
  if (d !== 0) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60; if (h < 0) h += 360;
  }
  if (s < 0.10) return l > 0.85 ? 'White' : 'Grey';
  if (l > 0.90 && s < 0.30) return 'White';
  if (h >= 20 && h <= 55) {
    if (s < 0.35 && l > 0.6) return 'Neutral';
    if (l < 0.5) return 'Brown';
    return 'Orange';
  }
  if (h < 20 || h >= 345) return l > 0.72 ? 'Pink' : 'Red';
  if (h < 45) return l < 0.5 ? 'Brown' : 'Orange';
  if (h < 66) return 'Yellow';
  if (h < 170) return 'Green';
  if (h < 255) return 'Blue';
  if (h < 300) return 'Purple';
  return l > 0.72 ? 'Pink' : 'Purple';
}
