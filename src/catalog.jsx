// Closest DMC floss to an arbitrary RGB color (Euclidean in RGB space).
function nearestDMC({ r, g, b }) {
  let best = null, bd = Infinity;
  for (const c of DMC) {
    const k = hexToRgb(c.hex);
    const d = (r - k.r) ** 2 + (g - k.g) ** 2 + (b - k.b) ** 2;
    if (d < bd) { bd = d; best = c; }
  }
  return best;
}
// Closest color within an explicit list (used to snap to a chosen palette).
function nearestInList({ r, g, b }, list) {
  let best = null, bd = Infinity;
  for (const c of list) {
    const k = hexToRgb(c.hex);
    const d = (r - k.r) ** 2 + (g - k.g) ** 2 + (b - k.b) ** 2;
    if (d < bd) { bd = d; best = c; }
  }
  return best;
}
