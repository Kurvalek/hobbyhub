// Quilt-top yardage. `qty` is the kit multiplier (e.g. a Coaster kit makes 4):
// we scale the patch COUNT and let the strip-nesting pack the extra pieces
// across the fabric width, rather than multiplying a full-width yardage by qty.
function calcYardage(count, bs, qty=1) {
  count = count*qty;
  if (!count) return { yards:0, cutSize:bs+SEAM, strips:0 };
  const cut=bs+SEAM, pps=Math.max(1,Math.floor(WOF/cut)), strips=Math.ceil(count/pps);
  return { yards: Math.ceil((strips*cut/36)*8)/8, cutSize:cut, strips };
}
function calcBacking(w,h,qty=1) {
  // Multi-unit kit of small pieces: nest the qty backing panels across the
  // usable fabric width instead of buying qty × a full-width single panel.
  if (qty > 1) {
    const cutW=w+2, cutH=h+2;                       // 1" margin per side, per unit
    const perRow=Math.max(1, Math.floor(WOF/cutW));
    const rows=Math.ceil(qty/perRow);
    const total=rows*cutH;                          // length of WOF-wide fabric
    const pieceW=Math.min(qty,perRow)*cutW;
    return { yards:Math.ceil((total/36)*8)/8, backingW:pieceW, backingH:total, widths:1 };
  }
  const bW=w+8, bH=h+8;
  const wA=Math.ceil(bW/WOF), wB=Math.ceil(bH/WOF);
  const pickA=wA*bH<=wB*bW, widths=pickA?wA:wB, total=pickA?wA*bH:wB*bW;
  return { yards:Math.ceil((total/36)*8)/8, backingW:bW, backingH:bH, widths };
}
function calcBinding(w,h,qty=1) {
  // Binding is linear trim: total length = qty × perimeter, cut into WOF strips.
  const perim=2*(w+h), totalPerim=perim*qty, strips=Math.ceil((totalPerim+10)/WOF);
  return { yards:Math.ceil((strips*2.5/36)*8)/8, strips, perimeter:totalPerim };
}
function fmtY(y) {
  if (!y) return "0 yd";
  const w=Math.floor(y), e=Math.round((y-w)*8);
  if (!e) return `${w} yd`;
  if (e===8) return `${w+1} yd`;
  const gcd=(a,b)=>b?gcd(b,a%b):a, g=gcd(e,8);
  return w ? `${w} ${e/g}/${8/g} yd` : `${e/g}/${8/g} yd`;
}
