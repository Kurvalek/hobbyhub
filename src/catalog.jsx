// Median-cut color quantization → top `count` colors, sorted by population.
function extractColors(imageData, count) {
  const data = imageData.data, pixels = [];
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] < 125) continue;
    pixels.push([data[i], data[i + 1], data[i + 2]]);
  }
  if (!pixels.length) return [];
  const rangeOf = b => {
    let mn = [255, 255, 255], mx = [0, 0, 0];
    for (const p of b) for (let c = 0; c < 3; c++) { if (p[c] < mn[c]) mn[c] = p[c]; if (p[c] > mx[c]) mx[c] = p[c]; }
    return Math.max(mx[0] - mn[0], mx[1] - mn[1], mx[2] - mn[2]);
  };
  const widestChannel = b => {
    let mn = [255, 255, 255], mx = [0, 0, 0];
    for (const p of b) for (let c = 0; c < 3; c++) { if (p[c] < mn[c]) mn[c] = p[c]; if (p[c] > mx[c]) mx[c] = p[c]; }
    const r = mx[0] - mn[0], g = mx[1] - mn[1], bl = mx[2] - mn[2];
    return r >= g && r >= bl ? 0 : g >= bl ? 1 : 2;
  };
  let buckets = [pixels];
  while (buckets.length < count) {
    buckets.sort((a, b) => rangeOf(b) - rangeOf(a));
    const big = buckets.shift();
    if (!big || big.length < 2) { if (big) buckets.unshift(big); break; }
    const ch = widestChannel(big);
    big.sort((x, y) => x[ch] - y[ch]);
    const mid = Math.floor(big.length / 2);
    buckets.push(big.slice(0, mid), big.slice(mid));
  }
  return buckets.map(b => {
    const n = b.length;
    let r = 0, g = 0, bl = 0;
    for (const p of b) { r += p[0]; g += p[1]; bl += p[2]; }
    return { r: r / n, g: g / n, b: bl / n, hex: rgbToHex(r / n, g / n, bl / n), pop: n };
  }).sort((a, b) => b.pop - a.pop);
}

